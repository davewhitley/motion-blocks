	$out[]   = '```';
	$out[]   = '';
	$out[]   = '`null` instead of a recipe means "no animation".';
	$out[]   = '';
	$out[]   = '## Top-level fields';
	$out[]   = '';
	$out[]   = '| Field | Values | What it means |';
	$out[]   = '|---|---|---|';
	foreach ( $schema['properties'] as $name => $prop ) {
		$values = isset( $prop['enum'] ) ? '`' . implode( '`, `', array_map( 'strval', $prop['enum'] ) ) . '`' : ( is_array( $prop['type'] ) ? implode( ' or ', $prop['type'] ) : $prop['type'] );
		$req    = in_array( $name, $schema['required'], true ) ? ' **Required.**' : '';
		$out[]  = '| `' . $name . '` | ' . $values . ' | ' . str_replace( '|', '\\|', $prop['description'] ) . $req . ' |';
	}
	$out[] = '';
	$out[] = '## Effect fields';
	$out[] = '';
	$out[] = 'Inside `effect`, `entry` and `exit`. Only `type` is required.';
	$out[] = '';
	$out[] = '| Field | Values | What it means |';
	$out[] = '|---|---|---|';
	foreach ( $schema['properties']['entry']['properties'] as $name => $prop ) {
		if ( 'type' === $name || 'direction' === $name ) {
