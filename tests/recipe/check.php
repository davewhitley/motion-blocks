mb_recipe_check(
	$mb_file === json_decode( wp_json_encode( mb_recipe_published_schema() ), true ),
	'schema/animation-recipe.v1.json matches motion_blocks_recipe_schema()',
	'Regenerate it: wp eval-file tests/recipe/check.php schema'
);
mb_recipe_check(
	file_exists( $mb_docs_file ) && file_get_contents( $mb_docs_file ) === mb_recipe_reference_markdown(),
	'schema/README.md (the reference) is up to date',
	'Regenerate it: wp eval-file tests/recipe/check.php schema'
);

echo "\nCoverage map (tests/recipe/coverage.json)\n";
$mb_coverage = json_decode( file_get_contents( __DIR__ . '/coverage.json' ), true );
$mb_schema   = motion_blocks_recipe_schema();
$mb_bad      = array();
foreach ( $mb_coverage['fields'] as $attr => $field ) {
	if ( ! isset( $mb_schema['properties'][ strtok( $field, '.' ) ] ) ) {
		$mb_bad[] = "{$attr} → {$field}";
	}
}
foreach ( $mb_coverage['effectFields'] as $suffix => $field ) {
	if ( ! isset( $mb_schema['properties']['entry']['properties'][ $field ] ) ) {
		$mb_bad[] = "{$suffix} → {$field}";
	}
}
mb_recipe_check( ! $mb_bad, 'every recipe field in the coverage map exists in the schema', implode( ', ', $mb_bad ) );
$mb_cat_types = wp_list_pluck( motion_blocks_recipe_effect_catalog(), 'type' );
$mb_all_types = array_values( array_unique( array_merge( $mb_shared_types = motion_blocks_shared_constants()['animationTypes'], motion_blocks_shared_constants()['entryTypes'], motion_blocks_shared_constants()['exitTypes'] ) ) );
sort( $mb_cat_types );
sort( $mb_all_types );
mb_recipe_check( $mb_cat_types === $mb_all_types, 'the effect catalog covers every effect', wp_json_encode( array_values( array_diff( $mb_all_types, $mb_cat_types ) ) ) );

