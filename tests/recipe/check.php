		if ( 'replay' === $name ) {
			$desc = 'Scroll Appear only. In `entry`: ' . $desc . ' In `exit`: ' . $schema['properties']['exit']['properties']['replay']['description'];
		}
		$out[] = '| `' . $name . '` | ' . $values . ' | ' . str_replace( '|', '\\|', $desc ) . ' |';
	}
	$out[] = '';
	$out[] = '## Effects';
	$out[] = '';
	$out[] = 'Where an effect can be used: `page-load` / `scroll-interactive` (in `effect`), `entry`, `exit`.';
	$out[] = '';
